    public static CharSequence tr(CharSequence text) {
        if (text == null) return null;
        if (text instanceof String) return tr((String) text);
        String original = text.toString();
        String translated = translateString(original);
        return translated.equals(original) ? text : translated;
    }
    public static String tr(String text) { return text == null ? null : translateString(text); }

    private static String translateString(String text) {
        String exact = LABELS.get(text);
        if (exact != null) return exact;
        if (text.indexOf('\n') != -1) {
            String[] lines = text.split("\\n", -1);
            for (int i = 0; i < lines.length; i++) lines[i] = translateLine(lines[i]);
            return String.join("\n", lines);
        }
        return translateLine(text);
    }
    private static String translateLine(String line) {
        String exact = LABELS.get(line);
        if (exact != null) return exact;
        // UI-only numeric status from Shiny Scanner; never alter protocol keys. 
        if (line.matches("All [0-9]+ nearby checked"))
            return line.replaceFirst("^All ([0-9]+) nearby checked$", "$1 locais próximos verificados");
        if (line.matches("[0-9]+ checked, [0-9]+ shinies"))
            return line.replaceFirst("^([0-9]+) checked, ([0-9]+) shinies$", "$1 verificados, $2 brilhantes");
        if (line.matches("[0-9]+/[0-9]+ in 24 h"))
            return line.replaceFirst("^([0-9]+/[0-9]+) in 24 h$", "$1 nas últimas 24 h");
        // A maior frase deve vencer: a ordem de HashMap nao e deterministica.
        String prefix = null;
        String suffix = null;
        for (String source : LABELS.keySet()) {
            if (source.length() < 2 || source.length() >= line.length()) continue;
            if ((source.endsWith(" ") || source.endsWith("~") || source.endsWith("(") || source.endsWith("–")) && line.startsWith(source)
                    && (prefix == null || source.length() > prefix.length())) {
                prefix = source;
            }
            if (source.startsWith(" ") && line.endsWith(source)
                    && (suffix == null || source.length() > suffix.length())) {
                suffix = source;
            }
        }
        if (prefix != null) {
            return LABELS.get(prefix) + translateLine(line.substring(prefix.length()));
        }
        if (suffix != null) {
            return translateLine(line.substring(0, line.length() - suffix.length())) + LABELS.get(suffix);
        }
        // Translate dynamic status clauses without changing stored keys or IDs.
        for (String separator : new String[]{"  |  ", " | ", "  ·  ", " · ", "; "}) {
            int split = line.indexOf(separator);
            if (split > 0) {
                String first = line.substring(0, split), second = line.substring(split + separator.length());
                String left = translateLine(first), right = translateLine(second);
                if (!left.equals(first) || !right.equals(second)) return left + separator + right;
            }
        }
        return line.replace("PGRazor", "PGBR");
    }
